// ---- database inspection ----

type Row = Record<string, unknown>;

function userTables(db: AppDatabase): string[] {
  return (
    db
      .prepare(
        `SELECT name FROM sqlite_master WHERE type = 'table'
         AND name NOT LIKE 'sqlite_%' ORDER BY name`,
      )
      .all() as { name: string }[]
  ).map((t) => t.name);
}

/** Every row of every table, keyed by rowid. */
function snapshot(db: AppDatabase): Map<string, Map<string, Row>> {
  return new Map(
    userTables(db).map((table) => [
      table,
      new Map(
        (
          db
            .prepare(`SELECT rowid AS __rowid, * FROM "${table}"`)
            .all() as Row[]
        ).map(({ __rowid, ...row }) => [String(__rowid), row]),
      ),
    ]),
  );
}

function rootpages(db: AppDatabase): Map<string, string> {
  return new Map(
    (
      db
        .prepare(
          `SELECT name, rootpage FROM sqlite_master WHERE type = 'table'
           AND name NOT LIKE 'sqlite_%'`,
        )
        .all() as { name: string; rootpage: bigint }[]
    ).map((t) => [t.name, String(t.rootpage)]),
  );
}

/**
 * After a migration: every table and row that existed before is still
 * there with the same values in the columns it had (new columns may be
 * added and backfilled), and no table was rebuilt (same rootpage).
 */
function expectPreserved(
  before: Map<string, Map<string, Row>>,
  roots: Map<string, string>,
  db: AppDatabase,
  label: string,
): void {
  const after = snapshot(db);
  const afterRoots = rootpages(db);
  for (const [table, rows] of before) {
    expect(after.has(table), `${label}: table ${table} kept`).toBe(true);
    expect(afterRoots.get(table), `${label}: ${table} not rebuilt`).toBe(
      roots.get(table),
    );
    const now = after.get(table)!;
    expect(now.size, `${label}: ${table} row count`).toBe(rows.size);
    for (const [rowid, row] of rows) {
      const current = now.get(rowid);
      expect(current, `${label}: ${table} rowid ${rowid} kept`).toBeDefined();
      for (const [column, value] of Object.entries(row)) {
        expect(current![column], `${label}: ${table}.${column}`).toEqual(value);
      }
    }
  }
}

function expectHealthy(db: AppDatabase): void {
  expect(db.pragma('integrity_check', { simple: true })).toBe('ok');
  expect(db.pragma('foreign_key_check')).toEqual([]);
  expect(readApplicationId(db)).toBe(APPLICATION_ID);
}

function normalizedSchema(db: AppDatabase): Record<string, string> {
  return Object.fromEntries(
    (
      db
        .prepare(
          `SELECT type, name, sql FROM sqlite_master
           WHERE sql IS NOT NULL AND name NOT LIKE 'sqlite_%' ORDER BY name`,
        )
        .all() as { type: string; name: string; sql: string }[]
    ).map((o) => [`${o.type} ${o.name}`, o.sql.replace(/\s+/g, ' ').trim()]),
  );
}

// ---- the app's commands on an existing database ----

function appOn(db: AppDatabase, dir: string, clock: { now(): Instant }) {
  const driver = new FakePrintDriver();
  const dialogs = new FakeDialogs();
  const services = createApplicationServices({
    db,
    clock,
    logDir: path.join(dir, 'logs'),
    assetsDir: path.join(dir, 'assets'),
    dataDir: dir,
    databasePath: path.join(dir, 'db.sqlite'),
    printDriver: driver,
    dialogs,
    restore: {},
    openPath: async () => '',
  });
  const commands = new Map(buildCommands(services).map((c) => [c.channel, c]));
  async function call<T = unknown>(
    channel: string,
    input?: unknown,
    windowId = ADMIN,
  ): Promise<T> {
    const result = (await executeCommand(
      commands.get(channel)!,
      { windowId },
      input,
      services.logger,
    )) as Result<T>;
    if (!result.ok) {
      // An unexpected error is only in the technical log: show its tail.
      const log = path.join(dir, 'logs', 'bengkelin.log');
      const detail = existsSync(log)
        ? readFileSync(log, 'utf8').trim().split('\n').at(-1)
        : '';
      throw new Error(
        `${channel}: ${JSON.stringify(result.error)} ${detail ?? ''}`,
      );
    }
    return result.value;
  }
  return { call, dialogs, driver };
}


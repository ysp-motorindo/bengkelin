/**
 * Task 18 / plan §4: "Populated previous-schema fixtures migrate without
 * database rebuilding" (spec 44, 64).
 *
 * 1. Every committed fixture `tests/fixtures/db/schema-vNNN-populated.sqlite`
 *    (generated by `npm run fixtures:db` through the real commands) opens
 *    and migrates to the latest bundled schema: integrity and foreign keys
 *    clean, every row kept, no table rebuilt, and the app's own commands
 *    work on it.
 * 2. A progressive upgrade: an empty database is migrated ONE version at a
 *    time; before each next migration the app writes representative rows
 *    that step's schema supports. Every migration must keep every existing
 *    row (and value) and every table's b-tree (rootpage), and at the end
 *    the schema equals a fresh install and EVERY trigger still fires.
 *
 * A future migration that must rewrite existing values (not only add and
 * backfill new columns) has to say so here explicitly, with its own test.
 */

